TEMPLATES: dict[str, tuple[PromptTemplate, ...]] = {
    PROOFREAD: _PROOFREAD,
    TRANSLATE: _TRANSLATE,
    ANALYZE: _ANALYZE,
    REWRITE: _REWRITE,
    SUMMARIZE: _SUMMARIZE,
}


def templates_for(direction: str) -> list[PromptTemplate]:
    return list(TEMPLATES.get(direction, ()))


def default_template(direction: str) -> PromptTemplate:
    """各方向的首个模板即默认。"""
    items = TEMPLATES.get(direction) or _ANALYZE
    return items[0]


def get_template(direction: str, template_id: str) -> PromptTemplate | None:
    for t in TEMPLATES.get(direction, ()):  # noqa: SIM110
        if t.id == template_id:
            return t
    return None
